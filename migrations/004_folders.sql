-- =============================================================================
-- TG Space Bot :: virtual folders (labels, not physical storage)
-- Idempotent: safe to execute multiple times.
-- =============================================================================
-- A folder only groups references to rows of ``files``; every byte still lives in
-- the Telegram storage group of the file's own category. Deleting a file cascades
-- to its folder links, and deleting a folder never touches the stored file.

create table if not exists public.folders (
    id          bigint      generated by default as identity primary key,
    user_id     bigint      not null,
    name        text        not null,
    created_at  timestamptz not null default timezone('utc', now())
);

-- One folder name per user, case-insensitive.
create unique index if not exists folders_user_name_key
    on public.folders (user_id, lower(name));

-- file_id is a bigint to match files.id (a bigint identity since 001 was
-- aligned with the live schema); folder_id is a bigint identity as well. Both
-- columns must have the same type as the keys they reference.
create table if not exists public.folder_files (
    folder_id   bigint      not null references public.folders(id) on delete cascade,
    file_id     bigint      not null references public.files(id)  on delete cascade,
    created_at  timestamptz not null default timezone('utc', now()),
    primary key (folder_id, file_id)
);

create index if not exists folder_files_file_idx
    on public.folder_files (file_id);

alter table public.folders      enable row level security;
alter table public.folder_files enable row level security;

comment on table public.folders is
    'Virtual folders: labels only, the files stay in their Telegram storage groups.';
comment on table public.folder_files is
    'Which stored file belongs to which virtual folder.';
